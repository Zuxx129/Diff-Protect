#!/usr/bin/env python3
"""Aggregate SD3 metrics into mode-level summary tables.

Input is the row-level CSV generated by code/metrics/compute_sd3_metrics.py.
The script is intentionally dependency-light and computes mean/std/count plus
threshold-based success rates when the necessary columns exist.
"""
from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path
from statistics import mean, pstdev


def _to_float(value):
    try:
        if value is None or value == "":
            return None
        return float(value)
    except Exception:
        return None


def _group_key(row, keys):
    return tuple(row.get(k, "") for k in keys)


def _success(row, args):
    linf = _to_float(row.get("linf_perturb_tensor_-1_1"))
    lpips_perturb = _to_float(row.get("lpips_perturb"))
    lpips_edit = _to_float(row.get("lpips_edit"))
    delta_clip = _to_float(row.get("delta_clip_prompt"))

    ok_linf = linf is not None and linf <= args.max_linf_tensor
    ok_imp = True if lpips_perturb is None else lpips_perturb <= args.max_lpips_perturb
    ok_edit = True if lpips_edit is None else lpips_edit >= args.min_lpips_edit
    ok_clip = True if delta_clip is None else delta_clip <= -args.min_clip_drop
    return ok_linf and ok_imp and ok_edit and ok_clip


def aggregate(rows, group_keys, args):
    groups = defaultdict(list)
    for row in rows:
        groups[_group_key(row, group_keys)].append(row)

    numeric_cols = sorted({
        k for row in rows for k, v in row.items()
        if _to_float(v) is not None and not k.endswith("path")
    })
    out_rows = []
    for key, items in sorted(groups.items()):
        out = {k: v for k, v in zip(group_keys, key)}
        out["count"] = len(items)
        successes = [_success(row, args) for row in items]
        out["success_rate"] = sum(successes) / max(len(successes), 1)
        for col in numeric_cols:
            vals = [_to_float(row.get(col)) for row in items]
            vals = [v for v in vals if v is not None]
            if not vals:
                continue
            out[f"{col}_mean"] = mean(vals)
            out[f"{col}_std"] = pstdev(vals) if len(vals) > 1 else 0.0
        out_rows.append(out)
    return out_rows


def read_csv(path):
    with Path(path).open("r", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def write_csv(rows, path):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    keys = sorted({k for row in rows for k in row.keys()}) or ["empty"]
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=keys)
        writer.writeheader()
        writer.writerows(rows)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--metrics", required=True)
    parser.add_argument("--out", default=None)
    parser.add_argument("--group-by", default="mode,epsilon,steps,sigma")
    parser.add_argument("--max-linf-tensor", type=float, default=2 * 16 / 255)
    parser.add_argument("--max-lpips-perturb", type=float, default=0.08)
    parser.add_argument("--min-lpips-edit", type=float, default=0.10)
    parser.add_argument("--min-clip-drop", type=float, default=0.02)
    args = parser.parse_args()

    rows = read_csv(args.metrics)
    group_keys = [x.strip() for x in args.group_by.split(",") if x.strip()]
    summary = aggregate(rows, group_keys, args)
    out = Path(args.out) if args.out else Path(args.metrics).with_name("summary_by_group.csv")
    write_csv(summary, out)
    meta = {
        "metrics": args.metrics,
        "out": str(out),
        "groups": len(summary),
        "rows": len(rows),
        "group_by": group_keys,
        "thresholds": {
            "max_linf_tensor": args.max_linf_tensor,
            "max_lpips_perturb": args.max_lpips_perturb,
            "min_lpips_edit": args.min_lpips_edit,
            "min_clip_drop": args.min_clip_drop,
        },
    }
    out.with_suffix(".json").write_text(json.dumps(meta, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(meta, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
